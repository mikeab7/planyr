/* NEW-1 (STATE-PLANE-AUDIT) — EVERY NAD83 SPCS ZONE, ALL 50 STATES.
 *
 * Before this change `resolveZone` knew three zones (TX South Central, CO North, CO Central) and returned null everywhere else;
 * overlay placement then fell back to the hardcoded EPSG:2278 grid, so a Tennessee / Georgia / Louisiana site was placed — and
 * its grid convergence computed — on Texas South Central.
 *
 * What is pinned here, and why each is the proof and not a claim:
 *  1. RED-PROOF — a Nashville point resolves to Tennessee (EPSG:2274). On main it resolves to null (and placement used Texas).
 *  2. GOLDEN — every one of the 122 registered zones, forward AND inverse, against reference values generated by PROJ (pyproj
 *     3.8.0 / PROJ 9.8.1, dev-time only: scripts/gen-state-plane-zones.py wrote test/fixtures/statePlaneGolden.json) to far
 *     better than 0.01 ft. Lambert, Transverse Mercator, Hotine Oblique Mercator; US-survey-foot, international-foot and metre.
 *  3. Alaska zone 1 (the oblique zone) has its OWN inline golden — values typed into this file, not read from the fixture.
 *  4. The three hand-written zones (TX South Central, CO North, CO Central) carry exactly EPSG's constants.
 *  5. UNITS are the legislated ones: international foot in AZ, MI, MT, ND, OR, SC; metres in HI; US survey foot elsewhere.
 *  6. COVERAGE — every one of the 3,144 counties in public/geo/county-polygons.json resolves to a zone of its own state, and so
 *     does every county key counties.js actually serves.
 *  7. NEVER TEXAS — nothing outside Texas can resolve to a Texas zone, and ground with no zone is null / an explicit local frame.
 */
