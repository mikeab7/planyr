const UNIT_M = { "us-ft": 1200 / 3937, ft: 0.3048, m: 1 };
const METRES_PER_DEG = 111319.49;
const FT_TOL = 0.005;   // the brief: "well under 0.01 ft"
/* gridConvergenceDeg is a numeric 1000-ft step that converts its east component with cos(lat) alone (a SPHERICAL east/north ratio
 * — pre-existing, shared by Texas and Colorado, and pinned by their goldens, so deliberately NOT changed here). Measured against
 * PROJ it is within 0.6% of the convergence plus 0.001° (Nashville 0.002°, Unalaska 0.016°, a fraction of a foot over a sheet). */
const convOk = (got, want) => Math.abs(got - want) <= 0.006 * Math.abs(want) + 0.001;

describe("1 · RED-PROOF — Nashville is Tennessee, not null and not Texas", () => {
  it("Davidson County, TN resolves to NAD83 / Tennessee (ftUS), EPSG:2274", () => {
    const z = resolveZone({ state: "TN", county: "Davidson", lat: 36.1627, lon: -86.7816 });
    expect(z).not.toBeNull();
    expect(z.epsg).toBe(2274);
    expect(z.id).toBe("tn");
    expect(z.state).toBe("TN");
    expect(z.unit).toBe("us-ft");
  });
  it("…by the county's routing key, by state alone, and by the bare point", () => {
    expect(resolveZone({ state: "TN", county: "tn_davidson" }).epsg).toBe(2274);
    expect(resolveZone({ state: "TN" }).epsg).toBe(2274);
    const pointOnly = resolveZone({ lat: 36.1627, lon: -86.7816 });
    expect(pointOnly.epsg).toBe(2274);
    expect(pointOnly.coarse).toBe(true);     // a county-less answer says it is coarse
  });
  it("a Nashville overlay is placed on Tennessee, and its convergence is Tennessee's (−0.4576°), not Texas South Central's", () => {
    expect(placementZone(36.1627, -86.7816).id).toBe("tn");
    expect(convOk(gridConvergenceDeg(36.1627, -86.7816, { state: "TN", county: "Davidson" }), -0.457579690)).toBe(true);
    const texasConv = gridConvergenceDeg(36.1627, -86.7816, { zone: SP_ZONES.tx_sc });
    expect(Math.abs(texasConv - -0.4576)).toBeGreaterThan(1);                // what main computed: a different number by degrees
  });
});

describe("2 · GOLDEN — every zone, forward and inverse, against PROJ", () => {
  it("the fixture and the registry cover exactly the same zones (122)", () => {
    expect(GOLDEN.zones.map((z) => z.id).sort()).toEqual(Object.keys(SP_ZONES).sort());
    expect(Object.keys(SP_ZONES).length).toBe(122);
  });
  it("the fixture spans every projection and unit it claims to (so the loop below cannot pass vacuously)", () => {
    const projs = new Set(Object.values(SP_ZONES).map((z) => z.proj || "lcc"));
    expect([...projs].sort()).toEqual(["hom", "lcc", "tm"]);
    const units = new Set(GOLDEN.zones.map((z) => z.unit));
    expect([...units].sort()).toEqual(["ft", "m", "us-ft"]);
    expect(GOLDEN.zones.every((z) => z.points.length >= 3)).toBe(true);
  });
  for (const g of GOLDEN.zones) {
    it(`${g.id} (EPSG:${g.epsg}, ${g.unit}) — ${g.points.length} points forward + inverse < ${FT_TOL} ft`, () => {
      const zone = SP_ZONES[g.id];
      expect(zone.epsg).toBe(g.epsg);
      expect(zone.unit).toBe(g.unit);
      const toFt = UNIT_M[zone.unit] / UNIT_M["us-ft"];
      for (const p of g.points) {
        const f = projectToZone(zone, p.lat, p.lon);
        expect(Math.hypot(f.x - p.x, f.y - p.y) * toFt, `forward ${p.lat},${p.lon}`).toBeLessThan(FT_TOL);
        const r = zoneToProject(zone, { x: p.x, y: p.y });
        const dN = (r.lat - p.lat) * METRES_PER_DEG, dE = (r.lon - p.lon) * METRES_PER_DEG * Math.cos((p.lat * Math.PI) / 180);
        expect(Math.hypot(dN, dE) / UNIT_M["us-ft"], `inverse ${p.lat},${p.lon}`).toBeLessThan(FT_TOL);
      }
    });
  }
});

