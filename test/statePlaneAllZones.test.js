describe("6 · COVERAGE — every county in the nationwide asset resolves to a zone of its own state", () => {
  const pointOf = (c) => ({ lat: (c.bbox[1] + c.bbox[3]) / 2 / POLYS.scale, lon: (c.bbox[0] + c.bbox[2]) / 2 / POLYS.scale });
  it("the asset really has all 3,144 counties (so the loop is not vacuous)", () => {
    expect(POLYS.counties.length).toBe(3144);
  });
  it("every county → a zone, and the zone's state is the county's state (DC rides Maryland)", () => {
    const bad = [];
    for (const c of POLYS.counties) {
      const pt = pointOf(c);
      // Grant County, WA is split by a parallel; the site's latitude decides. Alaska has no county zones: position decides.
      const z = resolveZone({ state: c.state, county: c.name, ...pt });
      const want = c.state === "DC" ? "MD" : c.state;
      if (!z || z.state !== want) bad.push(`${c.state} ${c.name} → ${z ? z.id : "null"}`);
    }
    expect(bad).toEqual([]);
  });
  it("a sample county in EVERY state resolves to a zone whose state matches (by name, by key, with a prefix)", () => {
    const seen = new Set();
    for (const c of POLYS.counties) {
      if (seen.has(c.state)) continue;
      seen.add(c.state);
      const pt = pointOf(c);
      const want = c.state === "DC" ? "MD" : c.state;
      expect(resolveZone({ state: c.state, county: c.name, ...pt })?.state, c.state).toBe(want);
      expect(resolveZone({ state: c.state.toLowerCase(), county: `${c.state.toLowerCase()}_${c.name.toLowerCase().replace(/[^a-z]/g, "")}`, ...pt })?.state, `${c.state} key`).toBe(want);
    }
    expect(seen.size).toBe(51);       // 50 states + DC
  });
  it("every county key counties.js serves resolves to a zone of its state", () => {
    const bad = [];
    let n = 0;
    for (const [key, rec] of Object.entries(COUNTIES_MAP)) {
      if (!rec || !rec.state || rec.statewide) continue;
      n++;
      const st = rec.state;
      // The county's own bbox centre stands in for a site (a county key alone carries no point).
      const bb = rec.bbox; const pt = bb ? { lat: (bb[0] + bb[2]) / 2, lon: (bb[1] + bb[3]) / 2 } : {};
      const z = resolveZone({ state: st, county: key, ...pt });
      if (!z || z.state !== st) bad.push(`${st} ${key} → ${z ? z.id : "null"}`);
    }
    expect(n).toBeGreaterThan(300);
    expect(bad).toEqual([]);
  });
  it("the county table names no county the asset does not have (typos / old names are explicit aliases)", () => {
    const names = new Set(POLYS.counties.map((c) => c.state + ":" + zoneForCountySlug(c.name)));
    const extra = [];
    for (const [st, zones] of Object.entries(COUNTY_TABLE)) {
      for (const list of Object.values(zones)) for (const k of list.split(",")) if (!names.has(`${st}:${k}`)) extra.push(`${st}:${k}`);
    }
    expect(extra).toEqual([]);
  });
});
// the JS slug, reached through the public resolver's own behaviour (zoneForCounty slugs internally) — recompute it here
const zoneForCountySlug = (c) =>
  String(c).normalize("NFKD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/^[a-z]{2}_/, "")
    .replace(/\b(city|and|county|parish|borough|census area|municipality|of)\b/g, "").replace(/[^a-z]/g, "");

