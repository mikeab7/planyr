#!/usr/bin/env node
// scripts/build-sequence-engine.mjs — bundles the Schedule's shared engine (src/shared/schedule/engine/*,
// the formula engine, ownership, range selection, health rules) into ONE plain script,
// public/sequence/engine.js, that the standalone Schedule page loads before its own code.
//
// This REPLACES the four paste-in sync scripts (sync-sequence-formula / -ownership / -selection and the
// health-engine copy): the page can't import from src/, so instead of keeping verbatim copies in sync by a
// test, the real modules are bundled here. The output is committed (the page and the ~70 ui-audit harnesses
// serve public/ directly) and test/sequenceEngineBundle.test.js fails if it is stale.
//
// Usage:  node scripts/build-sequence-engine.mjs            (writes public/sequence/engine.js)
//         node scripts/build-sequence-engine.mjs --check    (exit 1 if the committed file is stale)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { buildSync } from "esbuild";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const ENTRY = resolve(ROOT, "src/shared/schedule/engine/pageEntry.js");
export const OUT = resolve(ROOT, "public/sequence/engine.js");
const BANNER = "/* GENERATED by scripts/build-sequence-engine.mjs from src/shared/schedule/engine/* — do not edit; run `npm run build:sequence-engine`. */\n";

export function buildEngine() {
  const r = buildSync({
    entryPoints: [ENTRY], bundle: true, write: false, format: "iife", target: "es2020",
    legalComments: "none", charset: "utf8", logLevel: "silent",
  });
  return BANNER + r.outputFiles[0].text;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = buildEngine();
  if (process.argv.includes("--check")) {
    const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (cur !== next) { console.error("✗ public/sequence/engine.js is STALE — run: npm run build:sequence-engine"); process.exit(1); }
    console.log("✓ public/sequence/engine.js is up to date");
  } else {
    writeFileSync(OUT, next);
    console.log(`✓ wrote public/sequence/engine.js (${(next.length / 1024).toFixed(0)} KB)`);
  }
}
