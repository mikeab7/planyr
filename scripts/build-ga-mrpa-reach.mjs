#!/usr/bin/env node
/* NEW-1 (B2535200 second review, finding 2, 2026-10-30) — build src/workspaces/site-planner/lib/gaMrpaReach.js: the outline of the Metropolitan River Protection Act's
 * Chattahoochee corridor, for the places that have no live polygon to hand (the Protected Rivers click card, which is on the boot path).
 *
 * WHY: the card used the corridor's bounding box. A box is not the reach — its north-east corner sits over the impounded river at Buford Dam, and a 2,000-ft ribbon along a
 * 70-mile river fills a small part of its own box. The reach (O.C.G.A. 12-5-440 et seq.) is Buford Dam downstream to the downstream limits of Fulton and Douglas counties; ARC's
 * 2,000-ft corridor polygon is the published digitisation of it, so the outline is ARC's polygon, simplified (Douglas-Peucker, 25 m) and delta-encoded to 1e-5 degrees.
 *
 *   node scripts/build-ga-mrpa-reach.mjs        # needs network (services1.arcgis.com)
 */
import { writeFileSync } from "node:fs";

const OUT = new URL("../src/workspaces/site-planner/lib/gaMrpaReach.js", import.meta.url);
const URL_ = "https://services1.arcgis.com/Ug5xGQbHsD8zuZzM/arcgis/rest/services/Chattahoochee_River_Corridor_2000ft/FeatureServer/0/query";
const TOL_M = 25, SCALE = 1e5;
const fc = await (await fetch(`${URL_}?${new URLSearchParams({ where: "1=1", outFields: "FEATURE", outSR: "4326", f: "geojson" })}`)).json();
if (!fc.features || fc.features.length !== 1) throw new Error(`corridor → ${fc.features && fc.features.length} features (expected 1)`);
const g = fc.features[0].geometry;
if (g.type !== "Polygon") throw new Error("corridor is " + g.type);
const ring = g.coordinates[0].slice(0, -1);
const lat0 = ring.reduce((a, p) => a + p[1], 0) / ring.length;
const kx = 111320 * Math.cos((lat0 * Math.PI) / 180), ky = 110574;
const xy = ring.map((p) => [p[0] * kx, p[1] * ky]);
function dp(pts, lo, hi, keep) {
  let worst = -1, wi = -1; const [ax, ay] = pts[lo], [bx, by] = pts[hi]; const dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy) || 1;
  for (let i = lo + 1; i < hi; i++) { const d = Math.abs((pts[i][0] - ax) * dy - (pts[i][1] - ay) * dx) / L; if (d > worst) { worst = d; wi = i; } }
  if (worst > TOL_M) { keep[wi] = true; dp(pts, lo, wi, keep); dp(pts, wi, hi, keep); }
}
// a closed ring: split at the two points farthest apart so neither end is arbitrary
let ia = 0, ib = 0, far = 0;
for (let i = 0; i < xy.length; i += 7) for (let j = i; j < xy.length; j += 7) { const d = Math.hypot(xy[i][0] - xy[j][0], xy[i][1] - xy[j][1]); if (d > far) { far = d; ia = i; ib = j; } }
const keep = new Array(xy.length).fill(false); keep[ia] = keep[ib] = true;
dp(xy, ia, ib, keep);
const rot = xy.concat(xy.slice(0, ia + 1)); // second arc ib → end → ia
const keep2 = new Array(rot.length).fill(false); keep2[ib] = keep2[rot.length - 1] = true;
dp(rot, ib, rot.length - 1, keep2);
const out = [];
for (let i = 0; i < ring.length; i++) if (keep[i] || (i >= ib && keep2[i])) out.push(ring[i]);
if (out.length < 100 || out.length > 4000) throw new Error("simplified ring has " + out.length + " vertices");
let px = 0, py = 0; const nums = [];
for (const [x, y] of out) { const ix = Math.round(x * SCALE), iy = Math.round(y * SCALE); nums.push((ix - px).toString(36), (iy - py).toString(36)); px = ix; py = iy; }
const lngs = out.map((p) => p[0]), lats = out.map((p) => p[1]);
writeFileSync(OUT, `/* GENERATED by scripts/build-ga-mrpa-reach.mjs on 2026-10-30 — do not hand-edit. ARC's Chattahoochee 2,000-ft corridor (the Metropolitan River Protection Act reach, Buford Dam to the
 * downstream limits of Fulton and Douglas counties), ${ring.length} vertices simplified to ${out.length} (25 m), as [lng,lat] deltas in 1e-5 degrees, base 36. Read by georgiaRiverExclusions.js. */
export const GA_MRPA_REACH_SCALE = ${SCALE};
export const GA_MRPA_REACH_BBOX = Object.freeze({ lngMin: ${Math.min(...lngs).toFixed(5)}, lngMax: ${Math.max(...lngs).toFixed(5)}, latMin: ${Math.min(...lats).toFixed(5)}, latMax: ${Math.max(...lats).toFixed(5)} });
export const GA_MRPA_REACH = "${nums.join(",")}";
`);
console.log(`wrote ${out.length} vertices, ${nums.join(",").length} chars`);
