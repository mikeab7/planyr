/* Computes the lazy-layer index from the REAL layer files (used by scripts/build-lazy-layer-index.mjs and by the drift test — never by the app).
 * Per file: its ids in registry order, the ids a "Show above plan" lift can move, the ids that carry a corridor width, and the
 * states its rows serve (null when any row names no state, i.e. serves every state). That is everything an UNLOADED layer needs to be a
 * first-class citizen of saved settings: a stored on/off, opacity or lift for it is KEPT, never pruned as "unknown". */
import { LAZY_LAYER_FILES } from "./lazyLayerFiles.js";
import { configCanLift } from "./mapStack.js";

export async function buildLazyLayerIndex(files = LAZY_LAYER_FILES) {
  const out = {};
  for (const f of files) {
    const { layers } = f.pick(await f.load());
    const ids = Object.keys(layers);
    let states = new Set(); let any = false;
    for (const id of ids) {
      const s = layers[id].states;
      if (!Array.isArray(s) || !s.length) any = true; else s.forEach((x) => states.add(x));
    }
    out[f.key] = {
      states: any ? null : [...states].sort(),
      ids,
      lift: ids.filter((id) => configCanLift(layers[id])),
      corridor: ids.filter((id) => !!layers[id].corridorWidth),
    };
  }
  return out;
}

export const renderIndexModule = (index) =>
  `/* GENERATED by \`npm run layer-index\` (scripts/build-lazy-layer-index.mjs) — do not edit by hand. See lazyLayerFiles.js. */\nexport const LAZY_LAYER_INDEX = {\n${Object.entries(index).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n")}\n};\n`;
